"""Generates a stand-in libsteam_api.so source from a decompiled Steamworks.NET NativeMethods.cs.

Every native function Steamworks.NET can call exists and returns "nothing" (0 / false / an empty, zeroed
block for pointers), except: SteamAPI_Init -> true, SteamAPI_RestartAppIfNecessary -> false, and the pipe and
user handles -> 1, so the game sees a running Steam with no data and carries on without achievements,
leaderboards or cloud saves.
"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
code = open(src, encoding='utf-8').read()
pat = re.compile(r'\[DllImport\("steam_api"([^\]]*)\]\s*(?:\[return:[^\]]*\]\s*)?public static extern (\S+) (\w+)\(')
seen = {}
for m in pat.finditer(code):
    entry = re.search(r'EntryPoint\s*=\s*"(\w+)"', m.group(1))
    seen.setdefault(entry.group(1) if entry else m.group(3), m.group(2))
# IsSteamRunningOnSteamDeck: PortHub runs games on handhelds; games treat a Deck as fullscreen + controller.
TRUE = {'SteamAPI_Init', 'SteamAPI_InitSafe', 'SteamAPI_IsSteamRunning', 'SteamAPI_ISteamUtils_IsSteamRunningOnSteamDeck'}
ONE = {'SteamAPI_GetHSteamPipe', 'SteamAPI_GetHSteamUser', 'SteamGameServer_GetHSteamPipe', 'SteamGameServer_GetHSteamUser'}
FALSE_OVERRIDE = {'SteamAPI_RestartAppIfNecessary'}
lines = [
    '// Generated by PortHub (porthub/steam-stub/gen_steam_stub.py) from Steamworks.NET\'s NativeMethods:',
    '// a stand-in Steam API so Steamworks.NET games start on Android without Steam. Everything returns',
    '// "nothing"; Init succeeds; RestartAppIfNecessary says no. Pointers point at a zeroed block, which',
    '// also reads as an empty string.',
    '#include <stdint.h>',
    'static uint64_t porthub_zero[512];',
    '#define EXPORT __attribute__((visibility("default")))',
    '',
]
for name, ret in sorted(seen.items()):
    if ret in ('float', 'double'):
        lines.append(f'EXPORT {ret} {name}(void) {{ return 0; }}')
    elif ret == 'void':
        lines.append(f'EXPORT void {name}(void) {{ }}')
    elif ret == 'IntPtr':
        lines.append(f'EXPORT void *{name}(void) {{ return porthub_zero; }}')
    elif name in TRUE and name not in FALSE_OVERRIDE:
        lines.append(f'EXPORT int64_t {name}(void) {{ return 1; }}')
    elif name in ONE:
        lines.append(f'EXPORT int64_t {name}(void) {{ return 1; }}')
    else:
        lines.append(f'EXPORT int64_t {name}(void) {{ return 0; }}')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(seen), 'functions;', sum(1 for v in seen.values() if v == 'IntPtr'), 'pointers')
